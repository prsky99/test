class AdCoinError(ValueError):
    status = 400

    def __init__(self, code, message=None, status=None):
        super().__init__(message or code)
        self.code = code
        if status:
            self.status = status


class HoldRequired(AdCoinError):
    status = 409


def _ref(value, name):
    if type(value) is not str or not REF.fullmatch(value):
        raise AdCoinError('invalid_' + name)
    return value


def _won(value, name='amount_won', minimum=1, maximum=10_000_000):
    if type(value) is not int or not minimum <= value <= maximum:
        raise AdCoinError('invalid_' + name)
    if value % COIN_VALUE_WON:
        raise AdCoinError('invalid_' + name, 'Amounts must be whole coins (multiples of 10 won).')
    return value


MAX_LINES = 20


def bundle_lines(lines, price):
    """Validate a task bundle: lines of (provider, calls, won) that add up to the price.
    Free steps carry 0 won. None means a single-provider task."""
    if lines is None:
        return None
    if not isinstance(lines, list) or not 1 <= len(lines) <= MAX_LINES:
        raise AdCoinError('invalid_lines')
    clean = []
    for line in lines:
        if not isinstance(line, dict):
            raise AdCoinError('invalid_lines')
        provider = _ref(line.get('provider'), 'provider')
        calls, won = line.get('calls'), line.get('won')
        if type(calls) is not int or not 1 <= calls <= 1000 or type(won) is not int or not 0 <= won <= price:
            raise AdCoinError('invalid_lines')
        clean.append({'provider': provider, 'calls': calls, 'won': won})
    if sum(line['won'] for line in clean) != price:
        raise AdCoinError('invalid_lines', 'Bundle lines must add up to the price.')
    return clean


def coins(won):
    return won // COIN_VALUE_WON


def _day(at=None):
    """The Korean calendar day: caps, budgets and reports all use it."""
    return time.strftime('%Y-%m-%d', time.gmtime((at or now()) + DAY_OFFSET_SECONDS))


def day_start(at=None):
    """Start of the current Korean day, as a timestamp."""
    at = at or now()
    return at - ((at + DAY_OFFSET_SECONDS) % 86400)


def _down(value, unit=COIN_VALUE_WON):
    return value - value % unit


def _only(ids):
    """An id filter for re-checking a few known campaigns (values stay parameters)."""
    return ' AND c.id IN (' + ','.join('?' * len(ids)) + ')' if ids else ''


class AdCoinService:
    def __init__(self, database, signer, *, test_mode=True):
        self.db = database
        self.ledger = L.Ledger(database)
        self.signer = signer
        self.test_mode = test_mode
        self._feed_secret = self._secret('offer_feed_secret')
        if not self.db.one('SELECT 1 FROM ad_coin_totals LIMIT 1') and self.db.one('SELECT 1 FROM ad_coin_balances LIMIT 1'):
            self.ledger.rebuild_running_totals()

    # ---------- settings and circuit ----------
    def _secret(self, key):
        row = self.db.one('SELECT value FROM ad_coin_settings WHERE key=?', (key,))
        if row:
            return bytes.fromhex(json.loads(row['value']))
        value = secrets.token_bytes(32)
        with self.db.transaction() as db:
            db.execute('INSERT OR IGNORE INTO ad_coin_settings VALUES (?,?,?)', (key, json.dumps(value.hex()), now()))
        return bytes.fromhex(json.loads(self.db.one('SELECT value FROM ad_coin_settings WHERE key=?', (key,))['value']))

    SPLIT_CACHE_SECONDS = 5.0

    def split(self):
        """The admin's split, cached for SPLIT_CACHE_SECONDS (a change here applies at once)."""
        cached = getattr(self, '_split_cache', None)
        if cached and time.monotonic() - cached[0] < self.SPLIT_CACHE_SECONDS:
            return dict(cached[1])
        row = self.db.one("SELECT value FROM ad_coin_settings WHERE key='split_bps'")
        value = json.loads(row['value']) if row else dict(DEFAULT_SPLIT_BPS)
        self._split_cache = (time.monotonic(), value)
        return dict(value)

    def set_split(self, split):
        try:
            value = validate_split(split)
        except SettingsError as exc:
            raise AdCoinError('invalid_split', str(exc)) from None
        if value['operator'] + value['direct'] > 10000 - TASK_SHARE_BPS:
            raise AdCoinError('invalid_split', 'Operator and direct shares must leave room for task sponsorship.')
        with self.db.transaction() as db:
            db.execute("INSERT INTO ad_coin_settings VALUES ('split_bps',?,?) ON CONFLICT(key) DO UPDATE SET "
                       'value=excluded.value, updated_at=excluded.updated_at', (dumps(value), now()))
        self._split_cache = None
        return value

    def circuit(self):
        row = self.db.one('SELECT open, reason, changed_at FROM ad_coin_circuit WHERE id=1')
        return {'open': bool(row and row['open']), 'reason': row['reason'] if row else '',
                'changed_at': row['changed_at'] if row else None}

    def _set_circuit(self, is_open, reason):
        with self.db.transaction() as db:
            db.execute('INSERT INTO ad_coin_circuit VALUES (1,?,?,?) ON CONFLICT(id) DO UPDATE SET open=excluded.open, '
                       'reason=excluded.reason, changed_at=excluded.changed_at', (int(is_open), reason, now()))

    def open_circuit(self, reason):
        self._set_circuit(True, reason[:200])
        return self.circuit()

    def close_circuit(self):
        check = self.ledger.invariant()
        if not check['ok']:
            raise AdCoinError('invariant_failed', 'The ledger is not fully backed; the circuit stays open.', 409)
        self._set_circuit(False, '')
        return self.circuit()

    FULL_CHECK_EVERY = 500

    def _after_money_move(self):
        """O(1) backing check on every move; a full recount every FULL_CHECK_EVERY moves.

        On the dedicated PostgreSQL pool the recount runs on its own read-only snapshot in the
        background, so it never holds the writer lock; elsewhere it runs here as before."""
        self._moves = getattr(self, '_moves', 0) + 1
        if self._moves % self.FULL_CHECK_EVERY == 0:
            if not getattr(self.db, 'background_checks', False):
                return self.full_check()
            self._full_check_in_background()
        check = self.ledger.fast_invariant()
        if not check['ok'] and not self.circuit()['open']:
            self._set_circuit(True, 'invariant:' + ','.join(check['problems']))
        return check

    def _full_check_in_background(self):
        import threading
        if getattr(self, '_checking', None) and self._checking.is_alive():
            return                      # one recount at a time; the next due one starts after it

        def run():
            try:
                with self.db.read():
                    check = self.ledger.invariant()
                if not check['ok'] and not self.circuit()['open']:
                    self._set_circuit(True, 'invariant:' + ','.join(check['problems']))
                self.last_full_check = check
            except Exception as exc:        # a recount that cannot run must be visible, never silent
                import logging
                logging.getLogger('agent_market.ad_coin').error('AI AD Coin full check failed: %r', exc)
                self.last_full_check = {'ok': None, 'error': repr(exc)[:200]}
        self._checking = threading.Thread(target=run, name='ad-coin-full-check', daemon=True)
        self._checking.start()

    def daily_drift(self):
        """Campaigns whose kept daily spend differs from today's reservations (should be none)."""
        rows = self.db.all(
            "SELECT r.campaign_id, SUM(r.amount_won) AS s, MAX(COALESCE(d.spend_won, 0)) AS kept FROM "
            "ad_coin_reservations r LEFT JOIN ad_coin_campaign_daily d ON d.campaign_id=r.campaign_id AND d.day=? "
            "WHERE r.created_at>=? AND r.status IN ('reserved','awarded') GROUP BY r.campaign_id "
            "HAVING SUM(r.amount_won) <> MAX(COALESCE(d.spend_won, 0)) LIMIT 20", (_day(), day_start()))
        return [r['campaign_id'] for r in rows]

    def full_check(self):
        """Recount every balance and journal (also catches writes that bypassed the ledger)."""
        check = self.ledger.invariant()
        drift = self.daily_drift()
        if drift:
            check = dict(check, ok=False, problems=list(check['problems']) + ['daily_spend_drift'])
        if not check['ok'] and not self.circuit()['open']:
            self._set_circuit(True, 'invariant:' + ','.join(check['problems']))
        return check

    # ---------- wallets ----------
    def _ensure_wallet(self, user_ref, agent_ref=''):
        account = L.agent_wallet(user_ref, agent_ref) if agent_ref else L.user_wallet(user_ref)
        with self.db.transaction() as db:
            db.execute('INSERT OR IGNORE INTO ad_coin_wallets VALUES (?,?,?,?,?,?)',
                       (account, user_ref, 'agent' if agent_ref else 'user', agent_ref, now(), now()))
        return account

    def _ensure_wallets(self, user_ref, agent_ref):
        """The agent's wallet and the person's master wallet, created in one statement when missing."""
        if not agent_ref:
            account = self._ensure_wallet(user_ref)
            return account, account
        agent, master, at = L.agent_wallet(user_ref, agent_ref), L.user_wallet(user_ref), now()
        with self.db.transaction() as db:
            db.execute('INSERT OR IGNORE INTO ad_coin_wallets VALUES (?,?,?,?,?,?),(?,?,?,?,?,?)',
                       (agent, user_ref, 'agent', agent_ref, at, at, master, user_ref, 'user', '', at, at))
        return agent, master

    def _touch(self, account):
        with self.db.transaction() as db:
            db.execute('UPDATE ad_coin_wallets SET last_active_at=? WHERE account=?', (now(), account))

    def _wallet(self, account):
        row = self.db.one('SELECT * FROM ad_coin_wallets WHERE account=?', (account,))
        if not row:
            raise AdCoinError('unknown_wallet', status=404)
        return row

    def wallets(self, user_ref):
        """Read only: a person's own wallet is listed even before its first coin."""
        rows = list(self.db.all('SELECT * FROM ad_coin_wallets WHERE user_ref=? ORDER BY kind DESC, agent_ref '
                                'LIMIT 50', (user_ref,)))
        if not any(r['kind'] == 'user' for r in rows):
            rows.insert(0, {'account': L.user_wallet(user_ref), 'kind': 'user', 'agent_ref': '',
                            'last_active_at': now()})
        items = []
        for row in rows:
            won = self.ledger.balance(row['account'])
            items.append({'account': row['account'], 'kind': row['kind'], 'agent': row['agent_ref'] or None,
                          'available_coins': coins(won), 'available_won_value': won,
                          'last_active_at': int(row['last_active_at'])})
        vouchers = self.db.all("SELECT id, provider, task_ref, price_won, expires_at FROM ad_coin_vouchers "
                               "WHERE user_ref=? AND status='active' ORDER BY created_at", (user_ref,))
        return {'wallets': items, 'total_coins': sum(i['available_coins'] for i in items),
                'vouchers': [{'id': v['id'], 'provider': v['provider'], 'task_ref': v['task_ref'],
                              'coins': coins(v['price_won']), 'expires_at': int(v['expires_at'])} for v in vouchers],
                'cash_value': None, 'transferable': True, 'test_mode': self.test_mode}

    # ---------- campaigns (admin, test mode) ----------
    def create_campaign(self, *, advertiser, product, title, body, question, answer, public_url,
                        categories, bid_won):
        if product not in PRODUCTS:
            raise AdCoinError('invalid_product')
        if type(advertiser) is not str or not 2 <= len(advertiser.strip()) <= 80:
            raise AdCoinError('invalid_advertiser')
        if type(public_url) is not str or not PUBLIC_URL.fullmatch(public_url):
            raise AdCoinError('invalid_public_url', 'A public https copy of the offer is required.')
        if (not isinstance(categories, list) or not 1 <= len(categories) <= 8
                or any(type(c) is not str or not re.fullmatch(CATEGORY, c) for c in categories)):
            raise AdCoinError('invalid_categories')
        _won(bid_won, 'bid_won', 10, 1_000_000)
        try:
            creative = screen_creative(title, body, question, answer)
        except ScreeningRejected as exc:
            raise AdCoinError('creative_rejected', 'Creative rejected: ' + ', '.join(exc.reasons)) from None
        campaign_id = 'c_' + uuid.uuid4().hex[:20]
        with self.db.transaction() as db:
            db.execute('INSERT INTO ad_coin_campaigns VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)',
                       (campaign_id, advertiser.strip(), creative['title'], creative['body'], public_url,
                        dumps(sorted(set(categories))), product, bid_won, creative['question'],
                        creative['answer'], 'active', int(self.test_mode), now()))
            self._index_categories(db, campaign_id, categories)
        return self.campaign(campaign_id)

    @staticmethod
    def _index_categories(db, campaign_id, categories):
        db.execute('DELETE FROM ad_coin_campaign_categories WHERE campaign_id=?', (campaign_id,))
        for category in sorted(set(categories)):
            db.execute('INSERT INTO ad_coin_campaign_categories VALUES (?,?,?)',
                       (campaign_id, category, category.split('/', 1)[0]))

    def campaign(self, campaign_id):
        row = self.db.one('SELECT * FROM ad_coin_campaigns WHERE id=?', (campaign_id,))
        if not row:
            raise AdCoinError('unknown_campaign', status=404)
        return {'id': row['id'], 'advertiser': row['advertiser'], 'product': row['product'], 'title': row['title'],
                'body': row['body'], 'question': row['question'], 'public_url': row['public_url'],
                'categories': json.loads(row['categories']), 'bid_won': row['bid_won'], 'status': row['status'],
                'test': bool(row['test']), 'escrow_won': self.ledger.balance(L.escrow(row['id']))}

    def campaigns(self):
        return [self.campaign(r['id']) for r in self.db.all('SELECT id FROM ad_coin_campaigns ORDER BY created_at '
                                                            'LIMIT 500')]

    def set_campaign_status(self, campaign_id, status):
        if status not in ('active', 'paused'):
            raise AdCoinError('invalid_status')
        self.campaign(campaign_id)
        with self.db.transaction() as db:
            db.execute('UPDATE ad_coin_campaigns SET status=? WHERE id=?', (status, campaign_id))
        return self.campaign(campaign_id)

    def fund_campaign(self, campaign_id, amount_won, idem):
        """Test mode: a virtual deposit into the segregated pool."""
        self.campaign(campaign_id)
        _won(amount_won, maximum=100_000_000)
        with self.db.transaction():
            self.db.lock_rows('ad_coin_campaigns', [campaign_id])
            return self._fund(campaign_id, amount_won, idem)

    def _fund(self, campaign_id, amount_won, idem):
        try:
            self.ledger.post('fund', 'fund:' + idem, [(L.EXTERNAL_FUNDING, -amount_won),
                                                     (L.escrow(campaign_id), amount_won)],
                             {'campaign': campaign_id, 'virtual': self.test_mode})
        except L.Duplicate:
            pass
        self._after_money_move()
        return self.campaign(campaign_id)

    def refund_campaign(self, campaign_id, idem):
        self.expire()
        with self.db.transaction():
            self.db.lock_rows('ad_coin_campaigns', [campaign_id])
            return self._refund(campaign_id, idem)

    def _refund(self, campaign_id, idem):
        amount = self.ledger.balance(L.escrow(campaign_id))
        if amount:
            try:
                self.ledger.post('refund_escrow', 'refund_escrow:' + idem,
                                 [(L.escrow(campaign_id), -amount), (L.EXTERNAL_FUNDING, amount)],
                                 {'campaign': campaign_id})
            except L.Duplicate:
                pass
        self.set_campaign_status(campaign_id, 'paused')
        self._after_money_move()
        return self.campaign(campaign_id)

    # ---------- expiry ----------
    EXPIRE_EVERY_SECONDS = 5.0

    def _sweep(self):
        """The expiry sweep on request paths, at most every EXPIRE_EVERY_SECONDS per process. Each path
        also refuses an expired reservation or voucher itself, so a later sweep only returns the money."""
        at = time.monotonic()
        if at - getattr(self, '_swept_at', -1e9) >= self.EXPIRE_EVERY_SECONDS:
            self._swept_at = at
            if not getattr(self.db, 'background_checks', False):
                return self.expire()
            # On the dedicated pool the sweep runs on its own thread, one short transaction per
            # item, so it never holds a request's locks (and never orders locks against one).
            import threading
            if getattr(self, '_sweeping', None) and self._sweeping.is_alive():
                return

            def run():
                try:
                    self.expire()
                except Exception as exc:
                    import logging
                    logging.getLogger('agent_market.ad_coin').error('AI AD Coin expiry sweep failed: %r', exc)
            self._sweeping = threading.Thread(target=run, name='ad-coin-sweep', daemon=True)
            self._sweeping.start()

    def expire(self):
        at = now()
        for row in self.db.all("SELECT * FROM ad_coin_reservations WHERE status='reserved' AND expires_at<? "
                               "ORDER BY expires_at LIMIT 200", (at,)):
            self._release(row, 'expired')
        for row in self.db.all("SELECT v.*, r.campaign_id FROM ad_coin_vouchers v JOIN ad_coin_reservations r ON r.id=v.reservation_id "
                               "WHERE v.status='active' AND v.expires_at<? ORDER BY v.expires_at LIMIT 200", (at,)):
            with self.db.transaction() as db:
                self.db.lock_rows('ad_coin_campaigns', [row['campaign_id']])
                db.execute("UPDATE ad_coin_vouchers SET status='expired' WHERE id=? AND status='active'", (row['id'],))
                # Never catch inside a transaction: on PostgreSQL a caught error still fails the outer one.
                if not self.ledger.has('voucher_expired:' + row['id']):
                    self.ledger.post('voucher_expired', 'voucher_expired:' + row['id'],
                                     [(L.voucher(row['id']), -row['price_won']), (L.escrow(row['campaign_id']), row['price_won'])])

    @staticmethod
    def _daily(db, campaign_id, day, offers=0, views=0, spend=0, invalid=0, started=0, succeeded=0):
        """Per campaign and Korean day, updated in the same transaction as the event. Serving uses
        spend_won only to skip campaigns that cannot afford one more bid (the exact budget check still
        reads the reservations); reports read the rest."""
        db.execute('INSERT INTO ad_coin_campaign_daily VALUES (?,?,?,?,?,?,?,?) ON CONFLICT(campaign_id, day) DO '
                   'UPDATE SET offers=ad_coin_campaign_daily.offers+excluded.offers, '
                   'views=ad_coin_campaign_daily.views+excluded.views, '
                   'spend_won=ad_coin_campaign_daily.spend_won+excluded.spend_won, '
                   'invalid_refunded_won=ad_coin_campaign_daily.invalid_refunded_won+excluded.invalid_refunded_won, '
                   'runs_started=ad_coin_campaign_daily.runs_started+excluded.runs_started, '
                   'runs_succeeded=ad_coin_campaign_daily.runs_succeeded+excluded.runs_succeeded',
                   (campaign_id, day, offers, views, spend, invalid, started, succeeded))

    def _release(self, reservation, status):
        with self.db.transaction() as db:
            self.db.lock_rows('ad_coin_campaigns', [reservation['campaign_id']])   # lock order: campaign first
            changed = db.execute("UPDATE ad_coin_reservations SET status=? WHERE id=? AND status='reserved'",
                                 (status, reservation['id'])).rowcount
            if changed:
                self._daily(db, reservation['campaign_id'], _day(reservation['created_at']),
                            spend=-reservation['amount_won'])
                amount = self.ledger.balance(L.hold(reservation['id']))
                if amount:
                    self.ledger.post('release', 'release:' + reservation['id'],
                                     [(L.hold(reservation['id']), -amount), (L.escrow(reservation['campaign_id']), amount)])

    # ---------- quote ----------
    def _capped(self, user_ref, campaign_id):
        row = self.db.one('SELECT COUNT(*) AS n FROM ad_coin_exposures WHERE user_ref=? AND campaign_id=? AND day=?',
                          (user_ref, campaign_id, _day()))
        open_holds = self.db.one("SELECT COUNT(*) AS n FROM ad_coin_reservations WHERE user_ref=? AND campaign_id=? "
                                 "AND status='reserved'", (user_ref, campaign_id))
        return row['n'] + open_holds['n'] >= FREQUENCY_CAP_PER_DAY

    CHUNK = 100

    def _seen_today(self, user_ref):
        """Today's views plus open holds per campaign for this person (frequency caps)."""
        seen = {}
        for r in self.db.all("SELECT campaign_id, COUNT(*) AS n FROM ad_coin_exposures WHERE user_ref=? AND day=? "
                             "GROUP BY campaign_id UNION ALL SELECT campaign_id, COUNT(*) AS n FROM ad_coin_reservations "
                             "WHERE user_ref=? AND status='reserved' GROUP BY campaign_id LIMIT 2000",
                             (user_ref, _day(), user_ref)):
            seen[r['campaign_id']] = seen.get(r['campaign_id'], 0) + r['n']
        return seen

    def _active(self, product, user_ref, category='general', need=2, limit=50, seen=None, only=None):
        """Campaigns that may serve this person for this task category right now.

        Relevance has two levels (exact category 1.0, same top-level category 0.6), so each level
        is read separately in bid order, CHUNK rows at a time, until `need` eligible campaigns are
        found. Within a level the score is proportional to the bid and rows come in (bid DESC,
        id ASC) order, so the first `need` eligible ones are exactly that level's best; the union
        holds the overall best `need` and a second-price auction over it is exact. A campaign
        serves only if it is active, funded for one unit, within its schedule and daily budget,
        reviewed eligible, not paused, not excluding the category, its advertiser is active and
        this person is under its frequency cap."""
        columns = ("c.id, c.advertiser, c.title, c.body, c.question, c.public_url, c.categories, c.bid_won, "
                   "COALESCE(b.amount, 0) AS escrow_won, m.daily_budget_won, m.starts_at, m.ends_at, m.frequency_cap, "
                   "m.excluded, m.review_status, m.user_status, m.advertiser_id, COALESCE(d.spend_won, 0) AS spent_today, "
                   "a.verification AS adv_verification, a.status AS adv_status")
        head = ("SELECT " + columns + " FROM ad_coin_campaigns c LEFT JOIN ad_coin_balances b ON "
                "b.account='escrow:'||c.id LEFT JOIN ad_coin_campaign_meta m ON m.campaign_id=c.id "
                "LEFT JOIN ad_coin_campaign_daily d ON d.campaign_id=c.id AND d.day=? "
                "LEFT JOIN ad_coin_advertisers a ON a.id=m.advertiser_id "
                "WHERE c.product=? AND c.status='active' AND COALESCE(b.amount, 0) >= c.bid_won")
        if product != 'B1':
            # Skip in SQL what can never serve now (paused, not approved, budget spent); the rows that
            # pass are still checked exactly below, so this only saves reading the rest.
            head += (" AND (m.review_status IS NULL OR (m.review_status IN (?,?) AND m.user_status='enabled' AND "
                     "COALESCE(d.spend_won, 0) + c.bid_won <= CASE WHEN a.verification='verified' AND "
                     "a.status='active' AND m.review_status<>'eligible_limited' THEN m.daily_budget_won "
                     "WHEN m.daily_budget_won < ? THEN m.daily_budget_won ELSE ? END))")
            lead = (_day(), product) + SERVING_REVIEW + (LIMITED_DAILY_WON, LIMITED_DAILY_WON)
        else:
            lead = (_day(), product)
        tail = _only(only) + " ORDER BY c.bid_won DESC, c.id LIMIT ? OFFSET ?"
        extra = tuple(only or ())
        if category is None or only:    # the offer feed, or a re-check of known campaigns: one read
            parent = None if category is None else category.split('/', 1)[0]
            if parent and (category in BLOCKED_CATEGORIES or parent in BLOCKED_CATEGORIES):
                return []
            levels = [(head + tail, lead + extra)]
        else:
            parent = category.split('/', 1)[0]
            if category in BLOCKED_CATEGORIES or parent in BLOCKED_CATEGORIES:
                return []
            exact = ' AND c.id IN (SELECT campaign_id FROM ad_coin_campaign_categories WHERE category=?)'
            near = (' AND c.id IN (SELECT campaign_id FROM ad_coin_campaign_categories WHERE parent=?) AND c.id NOT IN '
                    '(SELECT campaign_id FROM ad_coin_campaign_categories WHERE category=?)')
            levels = [(head + exact + tail, lead + (category,) + extra),
                      (head + near + tail, lead + (parent, category) + extra)]
        seen = self._seen_today(user_ref) if seen is None else seen
        state = {'at': now(), 'today': day_start(), 'verified': {}}
        result = []
        for sql, scope in levels:
            found, offset = [], 0
            chunk = min(self.CHUNK, max(16, need * 4))
            while len(found) < need and len(result) + len(found) < limit:
                rows = self.db.all(sql, scope + (chunk, offset))
                offset += len(rows)
                found.extend(self._eligible(rows, product, category, parent, seen, state))
                if len(rows) < chunk:
                    break
            result.extend(found)
        return result[:limit]

    def _eligible(self, rows, product, category, parent, seen, state):
        """The rows of one chunk that may serve now, with their chosen creative (bounded reads)."""
        if not rows:
            return []
        at, today, verified = state['at'], state['today'], state['verified']
        ids = [r['id'] for r in rows]
        marks = ','.join('?' * len(ids))
        # Today's held and awarded amount per campaign, kept in the same transactions as every hold
        # and release (full_check verifies it against the reservations).
        spent = {r['id']: r['spent_today'] for r in rows}
        if product == 'B1':
            bids = {r['id']: r['bid_won'] for r in rows}
            for r in self.db.all("SELECT campaign_id, COUNT(*) AS n FROM ad_coin_offer_acks WHERE created_at>=? "
                                 "AND campaign_id IN (" + marks + ") GROUP BY campaign_id", (today,) + tuple(ids)):
                spent[r['campaign_id']] = spent.get(r['campaign_id'], 0) + r['n'] * bids[r['campaign_id']]
        creatives = {}
        for r in self.db.all(
                "SELECT id, campaign_id, title, body, question, public_url, weight, review_status FROM "
                "ad_coin_creatives WHERE removed_at IS NULL AND review_status IN ('eligible','eligible_limited') "
                "AND campaign_id IN (" + marks + ") LIMIT 1600", tuple(ids)):
            creatives.setdefault(r['campaign_id'], []).append(r)
        for r in rows:
            if r['advertiser_id']:
                verified[r['advertiser_id']] = (r['adv_verification'] if r['adv_status'] == 'active'
                                                else 'suspended')
        result = []
        for r in rows:
            cap = r['frequency_cap'] if r['frequency_cap'] is not None else FREQUENCY_CAP_PER_DAY
            if seen.get(r['id'], 0) >= cap or r['escrow_won'] < r['bid_won']:
                continue
            campaign = {'id': r['id'], 'advertiser': r['advertiser'], 'title': r['title'], 'body': r['body'],
                        'question': r['question'], 'public_url': r['public_url'], 'bid_won': r['bid_won'],
                        'categories': set(json.loads(r['categories'])), 'escrow_won': r['escrow_won'],
                        'creative_id': None}
            if r['review_status'] is not None:        # an advertiser-console campaign
                if r['review_status'] not in SERVING_REVIEW or r['user_status'] != 'enabled':
                    continue
                if r['starts_at'] > at or (r['ends_at'] is not None and r['ends_at'] <= at):
                    continue
                excluded = json.loads(r['excluded'])
                if category is not None and (category in excluded or parent in excluded):
                    continue
                if verified.get(r['advertiser_id']) == 'suspended':
                    continue
                daily = r['daily_budget_won']
                if verified.get(r['advertiser_id']) != 'verified' or r['review_status'] == 'eligible_limited':
                    daily = min(daily, LIMITED_DAILY_WON)
                if spent.get(r['id'], 0) + r['bid_won'] > daily:
                    continue
                options = creatives.get(r['id'])
                if not options:
                    continue
                pick = self._pick_creative(options)
                campaign.update(title=pick['title'], body=pick['body'], question=pick['question'],
                                public_url=pick['public_url'], creative_id=pick['id'],
                                daily_left_won=daily - spent.get(r['id'], 0))
            result.append(campaign)
        return result

    @staticmethod
    def _score(campaign, category):
        return campaign['bid_won'] * relevance(campaign['categories'], category) if category else campaign['bid_won']

    @staticmethod
    def _pick_creative(options):
        total = sum(max(1, o['weight']) for o in options)
        point = secrets.randbelow(total)
        for option in sorted(options, key=lambda o: o['id']):
            point -= max(1, option['weight'])
            if point < 0:
                return option
        return options[0]

    def _reserve(self, db, quote_id, campaign, product, user_ref, agent_ref, operator_ref, amount, price_won):
        reservation_id = 'h_' + uuid.uuid4().hex[:20]
        db.execute('INSERT INTO ad_coin_reservations VALUES (?,?,?,?,?,?,?,?,?,?,?,?)',
                   (reservation_id, quote_id, campaign['id'], product, user_ref, agent_ref, operator_ref, amount,
                    price_won, 'reserved', now(), now() + RESERVATION_TTL_SECONDS))
        self.ledger.post('reserve', 'reserve:' + reservation_id,
                         [(L.escrow(campaign['id']), -amount), (L.hold(reservation_id), amount)],
                         {'quote': quote_id, 'product': product})
        if campaign.get('creative_id'):
            db.execute('INSERT INTO ad_coin_reservation_creatives VALUES (?,?)', (reservation_id, campaign['creative_id']))
        self._daily(db, campaign['id'], _day(), offers=1, spend=amount)
        return reservation_id

    def quote(self, *, user_ref, agent_ref, operator_ref, selection, task):
        """`selection` is the organic recommendation as already returned; it is
        hashed, never read for ranking. `task` names what the organic step chose."""
        _ref(user_ref, 'user'); _ref(agent_ref, 'agent'); _ref(operator_ref, 'operator')
        if not isinstance(selection, (dict, list)) or len(dumps(selection)) > 32768:
            raise AdCoinError('invalid_selection')
        if not isinstance(task, dict):
            raise AdCoinError('invalid_task')
        provider = _ref(task.get('provider'), 'provider')
        task_ref = _ref(task.get('task_ref'), 'task_ref')
        price = _won(task.get('price_won'), 'price_won', 10, 1_000_000)
        category = task.get('category')
        if type(category) is not str or not re.fullmatch(CATEGORY, category):
            raise AdCoinError('invalid_category')
        lines = bundle_lines(task.get('lines'), price)
        self._sweep()
        digest = selection_digest(selection)
        quote_id = 'q_' + uuid.uuid4().hex[:20]
        agent_account, master_account = L.agent_wallet(user_ref, agent_ref), L.user_wallet(user_ref)
        # Phase 1, read only and outside every lock: balances, the circuit and every candidate. On the
        # dedicated pool the two products are read side by side on their own sessions; both are
        # checked again under the locks in phase 2, so separate snapshots are safe here.
        # Never while this thread already holds a session: waiting for more sessions while holding one
        # could exhaust the pool.
        parallel = (getattr(self.db, 'background_checks', False) and eligible_for_sponsorship(price)
                    and not self.db.in_transaction())
        if parallel:
            seen = self._seen_today(user_ref)
            pending = [self._readers().submit(self._active_read, 'S1', user_ref, category, 2, seen),
                       self._readers().submit(self._active_read, 'P2', user_ref, category, MAX_SPONSORED_OPTIONS, seen)]
        with self.db.read():
            split = self.split()
            held = {r['account'] for r in self.db.all('SELECT account FROM ad_coin_wallets WHERE account IN (?,?)',
                                                      (agent_account, master_account))}
            available = sum(r['amount'] for r in self.db.all(
                'SELECT amount FROM ad_coin_balances WHERE account IN (?,?)', (agent_account, master_account)))
            circuit = self.circuit()
            sponsorable = eligible_for_sponsorship(price) and not circuit['open']
            s1 = p2 = []
            if sponsorable and not parallel:
                seen = self._seen_today(user_ref)
                s1 = self._active('S1', user_ref, category, seen=seen)
                p2 = self._active('P2', user_ref, category, need=MAX_SPONSORED_OPTIONS, seen=seen)
        if parallel:
            s1, p2 = (f.result() for f in pending)
            if not sponsorable:
                s1 = p2 = []
        options, disclosures = [], []
        # Phase 2, under the writer lock: re-check only the campaigns that would be reserved with the
        # same eligibility rules, then reserve. A campaign that stopped qualifying meanwhile makes this
        # product fall back to a full read under the lock, so nothing is reserved on stale facts.
        with self.db.transaction() as db:
            self.db.lock_key('who:' + user_ref)       # this person's caps and holds
            if len(held) < 2:
                self._ensure_wallets(user_ref, agent_ref)
            if sponsorable and self.circuit()['open']:
                sponsorable, circuit = False, self.circuit()
            if sponsorable:
                fresh_seen = self._seen_today(user_ref)
                auction = run_task_auction(s1, category, price)
                chosen = self._coin_choice(p2, category, split, price, available)
                # Every campaign this quote may reserve, locked at once in id order (budgets until commit).
                self.db.lock_rows('ad_coin_campaigns', (auction['ranked'][:2] if auction else []) +
                                  [c['id'] for c in chosen])
                if auction:
                    keep = auction['ranked'][:2]
                    fresh = self._active('S1', user_ref, category, seen=fresh_seen, only=keep)
                    if {c['id'] for c in fresh} != set(keep):
                        auction = run_task_auction(self._active('S1', user_ref, category, seen=fresh_seen),
                                                   category, price)
                        if auction:
                            winner = auction['winner']['id']
                            self.db.lock_rows('ad_coin_campaigns', [winner])
                            if not self._active('S1', user_ref, category, seen=fresh_seen, only=[winner]):
                                auction = None
                    else:
                        auction = run_task_auction(fresh, category, price)
                if auction:
                    campaign = auction['winner']
                    rid = self._reserve(db, quote_id, campaign, 'S1', user_ref, agent_ref, operator_ref,
                                        auction['price_won'], price)
                    operator_won = _down(auction['price_won'] * split['operator'] // 10000)
                    options.append({'type': 'sponsored_run', 'reservation_id': rid, 'sponsor': campaign['advertiser'],
                                    'title': campaign['title'], 'body': campaign['body'],
                                    'question': campaign['question'], 'public_copy_url': campaign['public_url'],
                                    'view_ms': MIN_EXPOSURE_MS, 'grants': 'one run of this task',
                                    'coins_equivalent': coins(price)})
                    disclosures.append({'reservation_id': rid, 'paying_principal': campaign['advertiser'],
                                        'operator_reward_won': operator_won})
                for _attempt in range(2):
                    if not chosen:
                        break
                    keep = [c['id'] for c in chosen]
                    if _attempt:
                        self.db.lock_rows('ad_coin_campaigns', keep)
                    fresh = self._active('P2', user_ref, category, need=MAX_SPONSORED_OPTIONS, seen=fresh_seen,
                                         only=keep)
                    if {c['id'] for c in fresh} == set(keep):
                        chosen = self._coin_choice(fresh, category, split, price, available)
                        break
                    chosen = self._coin_choice(self._active('P2', user_ref, category, need=MAX_SPONSORED_OPTIONS,
                                                            seen=fresh_seen), category, split, price, available)
                else:
                    chosen = []          # still changing under us: offer no coin reward this time
                if chosen:
                    items = []
                    for campaign in chosen:
                        rid = self._reserve(db, quote_id, campaign, 'P2', user_ref, agent_ref, operator_ref,
                                            campaign['bid_won'], price)
                        items.append({'reservation_id': rid, 'sponsor': campaign['advertiser'],
                                      'title': campaign['title'], 'body': campaign['body'],
                                      'question': campaign['question'], 'public_copy_url': campaign['public_url'],
                                      'view_ms': MIN_EXPOSURE_MS,
                                      'coins': coins(_down(campaign['bid_won'] * split['user'] // 10000))})
                        disclosures.append({'reservation_id': rid, 'paying_principal': campaign['advertiser'],
                                            'operator_reward_won': _down(campaign['bid_won'] * split['operator'] // 10000)})
                    options.append({'type': 'coin_reward', 'items': items,
                                    'total_coins': sum(i['coins'] for i in items),
                                    'each_is_separate_approval': True})
            options.append({'type': 'pay_with_coins', 'available': available >= price,
                            'coins_needed': coins(price), 'coins_available': coins(available)})
            options.append({'type': 'direct_payment', 'available': False, 'reason': 'payments_closed_test_mode'})
            options.append({'type': 'free_result', 'available': True})
            packet = {
                'profile': 'ai-ad-coin-funding-packet-v1', 'quote_id': quote_id, 'test_mode': self.test_mode,
                'issued_at': int(now()), 'expires_at': int(now() + QUOTE_TTL_SECONDS),
                'selection_digest': digest,
                'organic_first': 'The organic recommendation was completed before this packet and did not see it.',
                'verified_upgrade_target': {'provider': provider, 'task_ref': task_ref, 'category': category,
                                            'bundle_lines': lines},
                'coin_quote_and_balance': {'price_coins': coins(price), 'available_coins': coins(available),
                                           'shortfall_coins': max(coins(price) - coins(available), 0),
                                           'coin_value_won': COIN_VALUE_WON, 'cash_value': None},
                'funding_options': options,
                'accountability_disclosure': disclosures,
                'user_consent_controls': {
                    'label': '[Ad | Sponsored offer]',
                    'approval_text': 'Approve each sponsored view separately. Declining keeps the free result.',
                    'decline_option': 'free_result', 'cooldown_choices_hours': [1, 24, 168],
                    'approval_scope': 'one view; never a payment, subscription or transfer'},
                'ai_generation_notice': AI_NOTICE,
                'equal_quality_statement': EQUAL_QUALITY,
                'sponsorship_unavailable_reason': (
                    ('no_matching_sponsor' if not any(o['type'] in ('sponsored_run', 'coin_reward') for o in options)
                     else None) if sponsorable else ('circuit_open' if circuit['open'] else 'task_below_minimum')),
            }
            packet['signature'] = self.signer.sign_payload(packet)
            packet['key_id'] = self.signer.kid
            db.execute('INSERT INTO ad_coin_quotes VALUES (?,?,?,?,?,?,?,?)',
                       (quote_id, user_ref, agent_ref, digest, dumps({'provider': provider, 'task_ref': task_ref,
                        'price_won': price, 'category': category, 'lines': lines}), dumps(options), now(), now() + QUOTE_TTL_SECONDS))
        self._after_money_move()
        return packet

    def _readers(self):
        """A small shared pool of reader threads for independent reads (dedicated sessions only)."""
        if getattr(self, '_reader_pool', None) is None:
            import concurrent.futures
            self._reader_pool = concurrent.futures.ThreadPoolExecutor(4, thread_name_prefix='ad-coin-read')
        return self._reader_pool

    def _active_read(self, product, user_ref, category, need, seen):
        with self.db.read():
            return self._active(product, user_ref, category, need=need, seen=seen)

    @staticmethod
    def _coin_choice(candidates, category, split, price, available):
        """The P2 campaigns that together cover the shortfall, each paying the top reward, or []."""
        p2 = sorted((c for c in candidates if relevance(c['categories'], category) > 0),
                    key=lambda c: (-c['bid_won'] * relevance(c['categories'], category), c['id']))
        if not p2:
            return []
        reward = _down(p2[0]['bid_won'] * split['user'] // 10000)
        count = coin_option_count(max(price - available, 0) or price, reward)
        chosen = [c for c in p2 if _down(c['bid_won'] * split['user'] // 10000) >= reward][:count or 0]
        if count and len(chosen) == count and all(c['escrow_won'] >= c['bid_won'] and
                                                  c.get('daily_left_won', c['bid_won']) >= c['bid_won']
                                                  for c in chosen):
            return chosen
        return []

    # ---------- consent and exposure ----------
    def _reservation(self, reservation_id, user_ref):
        row = self.db.one('SELECT * FROM ad_coin_reservations WHERE id=?', (reservation_id,))
        if not row or row['user_ref'] != user_ref:
            raise AdCoinError('unknown_reservation', status=404)
        return row

    def consent(self, *, user_ref, reservation_id):
        self._sweep()
        row = self._reservation(reservation_id, user_ref)
        if row['status'] != 'reserved' or row['expires_at'] < now():
            raise AdCoinError('reservation_closed', status=409)
        consent_id = 'k_' + uuid.uuid4().hex[:20]
        with self.db.transaction() as db:
            existing = db.execute('SELECT id FROM ad_coin_consents WHERE reservation_id=?', (reservation_id,)).fetchone()
            if existing:
                return {'consent_id': existing['id'], 'scope': 'one_view'}
            db.execute('INSERT INTO ad_coin_consents VALUES (?,?,?,?,NULL)', (consent_id, reservation_id, user_ref, now()))
        return {'consent_id': consent_id, 'scope': 'one_view', 'reservation_id': reservation_id}

    def decline(self, *, user_ref, reservation_id):
        row = self._reservation(reservation_id, user_ref)
        self._release(row, 'declined')
        self._after_money_move()
        return {'reservation_id': reservation_id, 'status': 'declined', 'next': 'free_result'}

    def exposure(self, *, user_ref, reservation_id, consent_id, displayed_ms, answer=None, foreground=True):
        self._sweep()
        row = self._reservation(reservation_id, user_ref)
        if row['status'] == 'reserved' and row['expires_at'] < now():
            raise AdCoinError('reservation_closed', status=409)
        consent = self.db.one('SELECT * FROM ad_coin_consents WHERE id=? AND reservation_id=?', (consent_id, reservation_id))
        if not consent or consent['user_ref'] != user_ref:
            raise AdCoinError('consent_required', 'Show the offer only after the person approves it.', 403)
        if row['status'] != 'reserved' or consent['used_at']:
            raise AdCoinError('reservation_closed', status=409)
        if type(displayed_ms) is not int or displayed_ms < MIN_EXPOSURE_MS or not foreground:
            raise AdCoinError('exposure_incomplete', 'The offer must be shown in the foreground for 15 seconds.', 422)
        campaign = self.campaign(row['campaign_id'])
        if row['product'] == 'P2' and (type(answer) is not str or not answer.strip()):
            raise AdCoinError('confirmation_required', 'Answer the one-question confirmation.', 422)
        matched = None
        if type(answer) is str and answer.strip():
            chosen = self.db.one('SELECT cr.answer FROM ad_coin_reservation_creatives rc JOIN ad_coin_creatives cr '
                                 'ON cr.id=rc.creative_id WHERE rc.reservation_id=?', (reservation_id,))
            stored = chosen['answer'] if chosen else self.db.one(
                'SELECT answer FROM ad_coin_campaigns WHERE id=?', (campaign['id'],))['answer']
            matched = answer.strip().lower() == stored.strip().lower()
        split = self.split()
        amount = row['amount_won']
        operator_won = _down(amount * split['operator'] // 10000)
        direct_won = _down(amount * split['direct'] // 10000)
        with self.db.transaction() as db:
            if not db.execute("UPDATE ad_coin_reservations SET status='awarded' WHERE id=? AND status='reserved'",
                              (reservation_id,)).rowcount:
                raise AdCoinError('reservation_closed', status=409)
            self._daily(db, row['campaign_id'], _day(row['created_at']), views=1)
            db.execute('UPDATE ad_coin_consents SET used_at=? WHERE id=?', (now(), consent_id))
            db.execute('INSERT INTO ad_coin_exposures VALUES (?,?,?,?,?,?,?)',
                       (reservation_id, campaign['id'], user_ref, _day(), displayed_ms, 'interaction', now()))
            if row['product'] == 'S1':
                task = json.loads(db.execute('SELECT task FROM ad_coin_quotes WHERE id=?', (row['quote_id'],)).fetchone()['task'])
                user_won = row['task_price_won']
                voucher_id = 'v_' + uuid.uuid4().hex[:20]
                target = L.voucher(voucher_id)
                db.execute('INSERT INTO ad_coin_vouchers VALUES (?,?,?,?,?,?,?,?,?)',
                           (voucher_id, reservation_id, user_ref, task['provider'], task['task_ref'], user_won,
                            'active', now(), now() + VOUCHER_TTL_SECONDS))
            else:
                user_won = _down(amount * split['user'] // 10000)
                target = self._ensure_wallet(user_ref, row['agent_ref'])
                self._touch(target)
                voucher_id = None
            platform_won = amount - user_won - operator_won - direct_won
            postings = [(L.hold(reservation_id), -amount), (target, user_won),
                        (L.operator_payable(row['operator_ref']), operator_won), (L.PLATFORM_DIRECT, direct_won),
                        (L.PLATFORM_REVENUE, platform_won)]
            journal = self.ledger.post('award', 'award:' + reservation_id, [p for p in postings if p[1]],
                                       {'product': row['product'], 'campaign': campaign['id']})
            exposure_receipt = self.signer.issue(self.db, 'exposure', user_ref, {
                'reservation_id': reservation_id, 'campaign_id': campaign['id'], 'paying_principal': campaign['advertiser'],
                'product': row['product'], 'displayed_ms': displayed_ms, 'foreground': True,
                'human_check': 'interaction', 'confirmation_matched': matched, 'consent_id': consent_id})
            reward = self.signer.issue(self.db, 'voucher' if voucher_id else 'reward', user_ref, {
                'journal_id': journal, 'reservation_id': reservation_id, 'voucher_id': voucher_id,
                'wallet': None if voucher_id else target, 'coins': coins(user_won),
                'operator_reward_won': operator_won, 'advertiser_paid_won': amount})
        self._after_money_move()
        return {'status': 'awarded', 'voucher_id': voucher_id, 'wallet': None if voucher_id else target,
                'coins': coins(user_won), 'receipts': [exposure_receipt, reward]}

    # ---------- transfers and sweep ----------
    def transfer(self, *, user_ref, from_account, to_account, coins_amount, idem, step_up=False, memo=''):
        source = self._wallet(from_account)
        if source['user_ref'] != user_ref:
            raise AdCoinError('not_your_wallet', status=403)
        if to_account == L.user_wallet(user_ref):
            self._ensure_wallet(user_ref)      # a person's own wallet always exists as a destination
        target = self._wallet(to_account)
        if from_account == to_account:
            raise AdCoinError('same_wallet')
        if type(coins_amount) is not int or coins_amount <= 0:
            raise AdCoinError('invalid_coins')
        amount = coins_amount * COIN_VALUE_WON
        other_person = target['user_ref'] != user_ref
        if memo_findings(memo):
            raise HoldRequired('transfer_held', 'The note looks like an instruction or a safety claim; '
                                                'the person must confirm this transfer directly.')
        if other_person and amount >= STEP_UP_TRANSFER_WON and not step_up:
            raise HoldRequired('step_up_required', 'Confirm transfers to another person with a fresh sign-in.')
        try:
            journal = self.ledger.post('transfer', 'transfer:' + user_ref + ':' + idem,
                                       [(from_account, -amount), (to_account, amount)],
                                       {'other_person': other_person})
        except L.Duplicate as dup:
            return {'status': 'already_done', 'journal_id': dup.journal_id}
        except L.LedgerError:
            raise AdCoinError('insufficient_coins', status=409) from None
        self._touch(from_account); self._touch(to_account)
        receipt = self.signer.issue(self.db, 'transfer', user_ref, {
            'journal_id': journal, 'from': from_account, 'to': to_account, 'coins': coins_amount,
            'to_other_person': other_person, 'new_value_created': False})
        self._after_money_move()
        return {'status': 'transferred', 'journal_id': journal, 'receipt': receipt}

    def sweep_agent(self, *, user_ref, agent_ref, reason='revoked'):
        account = L.agent_wallet(user_ref, agent_ref)
        self._wallet(account)
        master = self._ensure_wallet(user_ref)
        with self.db.transaction() as db:
            db.execute('UPDATE ad_coin_mandates SET revoked_at=? WHERE user_ref=? AND agent_ref=? AND revoked_at IS NULL',
                       (now(), user_ref, agent_ref))
        amount = self.ledger.balance(account)
        receipt = None
        if amount:
            journal = self.ledger.post('sweep', 'sweep:' + account + ':' + uuid.uuid4().hex,
                                       [(account, -amount), (master, amount)], {'reason': reason})
            receipt = self.signer.issue(self.db, 'sweep', user_ref, {
                'journal_id': journal, 'from': account, 'to': master, 'coins': coins(amount), 'reason': reason})
        self._after_money_move()
        return {'status': 'swept', 'coins': coins(amount), 'receipt': receipt}

    def sweep_dormant(self):
        cutoff = now() - DORMANT_AGENT_DAYS * 86400
        moved = []
        for row in self.db.all("SELECT * FROM ad_coin_wallets WHERE kind='agent' AND last_active_at<? "
                               "ORDER BY last_active_at LIMIT 500", (cutoff,)):
            if self.ledger.balance(row['account']):
                moved.append(self.sweep_agent(user_ref=row['user_ref'], agent_ref=row['agent_ref'],
                                              reason='dormant_agent'))
        return {'swept_wallets': len(moved), 'coins': sum(m['coins'] for m in moved)}

    # ---------- mandates ----------
    def create_mandate(self, *, user_ref, agent_ref, total_coins, per_task_coins, providers, days):
        _ref(agent_ref, 'agent')
        if type(total_coins) is not int or not 1 <= total_coins <= 100_000:
            raise AdCoinError('invalid_total')
        if type(per_task_coins) is not int or not 1 <= per_task_coins <= total_coins:
            raise AdCoinError('invalid_per_task')
        if not isinstance(providers, list) or not 1 <= len(providers) <= 20:
            raise AdCoinError('invalid_providers')
        providers = sorted({_ref(p, 'provider') for p in providers})
        if type(days) is not int or not 1 <= days <= MAX_MANDATE_DAYS:
            raise AdCoinError('invalid_days', 'Mandates last at most 30 days.')
        self._ensure_wallet(user_ref, agent_ref)
        mandate_id = 'm_' + uuid.uuid4().hex[:20]
        with self.db.transaction() as db:
            db.execute('INSERT INTO ad_coin_mandates VALUES (?,?,?,?,?,?,0,?,?,NULL)',
                       (mandate_id, user_ref, agent_ref, total_coins * COIN_VALUE_WON, per_task_coins * COIN_VALUE_WON,
                        dumps(providers), now(), now() + days * 86400))
        mandate = self.mandate(mandate_id, user_ref)
        mandate['receipt'] = self.signer.issue(self.db, 'mandate', user_ref, {k: v for k, v in mandate.items()})
        return mandate

    def mandate(self, mandate_id, user_ref):
        row = self.db.one('SELECT * FROM ad_coin_mandates WHERE id=? AND user_ref=?', (mandate_id, user_ref))
        if not row:
            raise AdCoinError('unknown_mandate', status=404)
        state = 'revoked' if row['revoked_at'] else ('expired' if row['expires_at'] < now() else 'active')
        return {'id': row['id'], 'agent': row['agent_ref'], 'total_coins': coins(row['total_won']),
                'per_task_coins': coins(row['per_task_won']), 'spent_coins': coins(row['spent_won']),
                'providers': json.loads(row['providers']), 'expires_at': int(row['expires_at']), 'state': state}

    def mandates(self, user_ref):
        return [self.mandate(r['id'], user_ref) for r in
                self.db.all('SELECT id FROM ad_coin_mandates WHERE user_ref=? ORDER BY created_at DESC LIMIT 100',
                            (user_ref,))]

    def revoke_mandate(self, mandate_id, user_ref):
        self.mandate(mandate_id, user_ref)
        with self.db.transaction() as db:
            db.execute('UPDATE ad_coin_mandates SET revoked_at=? WHERE id=? AND revoked_at IS NULL', (now(), mandate_id))
        return self.mandate(mandate_id, user_ref)

    # ---------- spending, execution and settlement ----------
    def spend(self, *, user_ref, wallet, provider, task_ref, price_coins, idem, actor='user', agent_ref='',
              mandate_id=None, memo='', lines=None):
        """Coins pay a provider's task. An agent acting alone needs a live mandate
        that covers the provider, the per-task limit and the remaining total."""
        source = self._wallet(wallet)
        if source['user_ref'] != user_ref:
            raise AdCoinError('not_your_wallet', status=403)
        provider = _ref(provider, 'provider'); task_ref = _ref(task_ref, 'task_ref')
        if type(price_coins) is not int or not 1 <= price_coins <= 100_000:
            raise AdCoinError('invalid_price')
        price = price_coins * COIN_VALUE_WON
        lines = bundle_lines(lines, price)
        if memo_findings(memo):
            raise HoldRequired('spend_held', 'The person must confirm this payment directly.')
        if actor == 'agent':
            if not mandate_id:
                raise HoldRequired('mandate_required', 'The person must approve this payment or grant a mandate.')
            row = self.db.one('SELECT * FROM ad_coin_mandates WHERE id=? AND user_ref=?', (mandate_id, user_ref))
            if (not row or row['revoked_at'] or row['expires_at'] < now() or row['agent_ref'] != agent_ref
                    or source['agent_ref'] not in ('', agent_ref)):
                raise HoldRequired('mandate_invalid', 'The mandate is missing, expired, revoked or for another agent.')
            allowed = set(json.loads(row['providers']))
            needed = {line['provider'] for line in lines if line['won']} if lines else {provider}
            if not needed <= allowed or price > row['per_task_won'] \
                    or row['spent_won'] + price > row['total_won']:
                raise HoldRequired('mandate_exceeded', 'This payment is outside the mandate; ask the person.')
        elif actor != 'user':
            raise AdCoinError('invalid_actor')
        execution_id = 'x_' + uuid.uuid4().hex[:20]
        earlier = self.db.one('SELECT id FROM ad_coin_journals WHERE idem=?', ('spend:' + user_ref + ':' + idem,))
        if earlier:
            return {'status': 'already_done', 'journal_id': earlier['id']}
        if self.ledger.balance(wallet) < price:
            raise AdCoinError('insufficient_coins', status=409)
        try:
            with self.db.transaction() as db:
                journal = self.ledger.post('spend', 'spend:' + user_ref + ':' + idem,
                                           [(wallet, -price), (L.inflight(execution_id), price)],
                                           {'provider': provider})
                db.execute('INSERT INTO ad_coin_executions VALUES (?,?,?,?,?,?,?,?,NULL,?,NULL)',
                           (execution_id, user_ref, provider, task_ref, price, 'coins', wallet, 'running', now()))
                self._insert_lines(db, execution_id, lines)
                if actor == 'agent':
                    db.execute('UPDATE ad_coin_mandates SET spent_won=spent_won+? WHERE id=?', (price, mandate_id))
        except L.Duplicate as dup:
            return {'status': 'already_done', 'journal_id': dup.journal_id}
        except L.LedgerError:
            raise AdCoinError('insufficient_coins', status=409) from None
        self._touch(wallet)
        self._after_money_move()
        return {'status': 'running', 'execution_id': execution_id, 'journal_id': journal,
                'provider_request': self.provider_request(execution_id)}

    def redeem_voucher(self, *, user_ref, voucher_id):
        row = self.db.one('SELECT * FROM ad_coin_vouchers WHERE id=? AND user_ref=?', (voucher_id, user_ref))
        if not row:
            raise AdCoinError('unknown_voucher', status=404)
        if row['status'] != 'active' or row['expires_at'] < now():
            raise AdCoinError('voucher_closed', status=409)
        execution_id = 'x_' + uuid.uuid4().hex[:20]
        task = self.db.one('SELECT q.task FROM ad_coin_vouchers v JOIN ad_coin_reservations r ON r.id=v.reservation_id '
                           'JOIN ad_coin_quotes q ON q.id=r.quote_id WHERE v.id=?', (voucher_id,))
        lines = json.loads(task['task']).get('lines') if task else None
        with self.db.transaction() as db:
            db.execute("UPDATE ad_coin_vouchers SET status='redeemed' WHERE id=?", (voucher_id,))
            self.ledger.post('redeem', 'redeem:' + voucher_id + ':' + execution_id,
                             [(L.voucher(voucher_id), -row['price_won']), (L.inflight(execution_id), row['price_won'])])
            db.execute('INSERT INTO ad_coin_executions VALUES (?,?,?,?,?,?,?,?,NULL,?,NULL)',
                       (execution_id, user_ref, row['provider'], row['task_ref'], row['price_won'], 'voucher',
                        voucher_id, 'running', now()))
            self._insert_lines(db, execution_id, lines)
        self._after_money_move()
        return {'status': 'running', 'execution_id': execution_id,
                'provider_request': self.provider_request(execution_id)}

    def provider_request(self, execution_id):
        """What the provider receives. It never says how the run was funded, so a
        sponsored run cannot be served differently from a paid one."""
        row = self.db.one('SELECT id, provider, task_ref FROM ad_coin_executions WHERE id=?', (execution_id,))
        request = {'execution_id': row['id'], 'provider': row['provider'], 'task_ref': row['task_ref']}
        lines = self._lines_of(execution_id)
        if lines:
            request['lines'] = [{'position': l['position'], 'provider': l['provider'], 'calls': l['calls']} for l in lines]
        return request

    def _insert_lines(self, db, execution_id, lines):
        for position, line in enumerate(lines or []):
            db.execute('INSERT INTO ad_coin_execution_lines VALUES (?,?,?,?,?,?)',
                       (execution_id, position, line['provider'], line['calls'], line['won'], 'running'))

    def _lines_of(self, execution_id):
        return self.db.all('SELECT * FROM ad_coin_execution_lines WHERE execution_id=? ORDER BY position', (execution_id,))

    def complete(self, *, execution_id, ok, result_digest=None, line_results=None):
        """Finish a run. For a bundle, `line_results` lists success per line in
        order; successful lines are paid to their providers and the rest goes
        back to whoever funded it (the wallet, or the sponsor's escrow)."""
        row = self.db.one('SELECT * FROM ad_coin_executions WHERE id=?', (execution_id,))
        if not row:
            raise AdCoinError('unknown_execution', status=404)
        if row['status'] != 'running':
            raise AdCoinError('execution_closed', status=409)
        lines = self._lines_of(execution_id)
        # Per line: True/False for the whole line, or the number of calls that succeeded.
        if line_results is None:
            results = [bool(ok)] * len(lines)
        elif lines and isinstance(line_results, list) and len(line_results) == len(lines) and all(
                type(r) is bool or (type(r) is int and 0 <= r <= line['calls'])
                for r, line in zip(line_results, lines)):
            results = line_results
        else:
            raise AdCoinError('invalid_line_results')
        price = row['price_won']
        if lines:
            def earned(line, result):
                if type(result) is bool:
                    return line['won'] if result else 0
                return line['won'] * result // line['calls']
            paid_lines = [(l, earned(l, r)) for l, r in zip(lines, results)]
            paid = sum(won for _, won in paid_lines)
            any_ok = any(won > 0 or (r is True) for (_, won), r in zip(paid_lines, results))
        else:
            paid = price if ok else 0
            any_ok = bool(ok)
        refund = price - paid
        if any_ok and (type(result_digest) is not str or not re.fullmatch(r'sha256:[0-9a-f]{64}', result_digest)):
            raise AdCoinError('result_digest_required')
        outcome = 'succeeded' if refund == 0 and any_ok else ('refunded' if not any_ok else 'partial')
        with self.db.transaction() as db:
            db.execute('UPDATE ad_coin_executions SET status=?, result_digest=?, finished_at=? WHERE id=?',
                       (outcome, result_digest, now(), execution_id))
            postings = [(L.inflight(execution_id), -price)]
            if lines:
                for line, won in paid_lines:
                    state = 'succeeded' if won == line['won'] and (won or results[line['position']] is True) \
                        else ('partial' if won else 'refunded')
                    db.execute('UPDATE ad_coin_execution_lines SET status=? WHERE execution_id=? AND position=?',
                               (state, execution_id, line['position']))
                    if won:
                        postings.append((L.provider_payable(line['provider']), won))
            elif paid:
                postings.append((L.provider_payable(row['provider']), paid))
            refund_to = None
            if refund:
                if row['source'] != 'voucher':
                    refund_to = row['source_ref']
                elif not any_ok:
                    refund_to = L.voucher(row['source_ref'])
                    db.execute("UPDATE ad_coin_vouchers SET status='active' WHERE id=?", (row['source_ref'],))
                else:
                    campaign = db.execute('SELECT r.campaign_id FROM ad_coin_vouchers v JOIN ad_coin_reservations r '
                                          'ON r.id=v.reservation_id WHERE v.id=?', (row['source_ref'],)).fetchone()
                    refund_to = L.escrow(campaign['campaign_id'])
                postings.append((refund_to, refund))
            merged = {}
            for account, amount in postings:
                merged[account] = merged.get(account, 0) + amount
            journal = self.ledger.post({'succeeded': 'complete', 'refunded': 'refund'}.get(outcome, 'partial'),
                                       'finish:' + execution_id, [(a, v) for a, v in merged.items() if v])
            receipt = self.signer.issue(self.db, 'refund' if outcome == 'refunded' else 'execution', row['user_ref'], {
                'journal_id': journal, 'execution_id': execution_id, 'provider': row['provider'],
                'task_ref': row['task_ref'], 'coins': coins(price), 'paid_won': paid, 'refunded_won': refund,
                'refunded_to': None if not refund_to else refund_to.split(':', 1)[0],
                'line_results': results or None, 'funded_by': row['source'],
                'result_digest': result_digest, 'outcome': outcome})
        self._after_money_move()
        return {'status': outcome, 'paid_won': paid, 'refunded_won': refund, 'receipt': receipt}

    def settle_provider(self, provider, idem):
        """Test mode: a virtual payout of everything owed to one provider."""
        account = L.provider_payable(_ref(provider, 'provider'))
        amount = self.ledger.balance(account)
        if not amount:
            return {'status': 'nothing_due', 'won': 0}
        try:
            journal = self.ledger.post('settle', 'settle:' + idem, [(account, -amount), (L.EXTERNAL_PAYOUT, amount)],
                                       {'provider': provider, 'virtual': self.test_mode})
        except L.Duplicate as dup:
            return {'status': 'already_done', 'journal_id': dup.journal_id}
        receipt = self.signer.issue(self.db, 'settlement', 'provider:' + provider, {
            'journal_id': journal, 'provider': provider, 'won': amount, 'virtual': self.test_mode,
            'platform_margin_taken_on_coins': False})
        self._after_money_move()
        return {'status': 'settled', 'won': amount, 'receipt': receipt}

    # ---------- signed sponsor offer feed (agents) ----------
    def _offer_token(self, campaign_id, operator_ref, day):
        message = (campaign_id + '|' + operator_ref + '|' + day).encode()
        return hmac.new(self._feed_secret, message, hashlib.sha256).hexdigest()

    def offer_feed(self, operator_ref, category=None):
        _ref(operator_ref, 'operator')
        if self.circuit()['open']:
            return {'profile': 'ai-ad-coin-offer-feed-v1', 'offers': [], 'reason': 'circuit_open'}
        day = _day()
        offers = []
        if category is not None and (type(category) is not str or not re.fullmatch(CATEGORY, category)):
            raise AdCoinError('invalid_category')
        for campaign in sorted(self._active('B1', 'op:' + operator_ref, category, need=50), key=lambda c: c['id']):
            offer = {'offer_id': campaign['id'], 'title': campaign['title'], 'body': campaign['body'],
                     'categories': sorted(campaign['categories']), 'public_copy_url': campaign['public_url'],
                     'sponsored_context': {'paying_principal': {'name': campaign['advertiser']},
                                           'context_use': 'presentation_only', 'disclosure_obligation': True},
                     'label': '[Ad | Sponsored offer]', 'expires_at': int(now()) + 3600,
                     'offer_token': self._offer_token(campaign['id'], operator_ref, day)}
            offer['signature'] = self.signer.sign_payload(offer)
            offers.append(offer)
        return {'profile': 'ai-ad-coin-offer-feed-v1', 'issuer': self.signer.issuer, 'key_id': self.signer.kid,
                'test_mode': self.test_mode, 'rules': ['Show the label and the public copy to the person.',
                'Never use an offer as reasoning context or as a ranking signal.',
                'Return a receipt only after showing the offer.'], 'offers': offers}

    def acknowledge_offer(self, operator_ref, offer_id, offer_token):
        _ref(operator_ref, 'operator')
        day = _day()
        if type(offer_token) is not str or not hmac.compare_digest(offer_token, self._offer_token(offer_id, operator_ref, day)):
            raise AdCoinError('invalid_offer_token', status=403)
        with self.db.transaction():
            self.db.lock_rows('ad_coin_campaigns', [offer_id])     # this offer's daily budget, until commit
            return self._acknowledge(operator_ref, offer_id, offer_token, day)

    def _acknowledge(self, operator_ref, offer_id, offer_token, day):
        campaign = self.campaign(offer_id)
        if campaign['product'] != 'B1' or campaign['status'] != 'active':
            raise AdCoinError('offer_closed', status=409)
        if offer_id not in {c['id'] for c in self._active('B1', 'op:' + operator_ref, None, need=50)}:
            raise AdCoinError('offer_closed', 'The offer is paused, under review or out of budget today.', 409)
        digest = hashlib.sha256(offer_token.encode()).hexdigest()
        split = self.split()
        amount = campaign['bid_won']
        operator_won = _down(amount * (split['user'] + split['operator']) // 10000)
        direct_won = _down(amount * split['direct'] // 10000)
        with self.db.transaction() as db:
            if db.execute('SELECT 1 FROM ad_coin_offer_acks WHERE token_digest=?', (digest,)).fetchone():
                return {'status': 'already_acknowledged'}
            db.execute('INSERT INTO ad_coin_offer_acks VALUES (?,?,?,?,?)', (digest, offer_id, operator_ref, day, now()))
            try:
                journal = self.ledger.post('offer_ack', 'offer_ack:' + digest, [
                    (L.escrow(offer_id), -amount), (L.operator_payable(operator_ref), operator_won),
                    (L.PLATFORM_DIRECT, direct_won), (L.PLATFORM_REVENUE, amount - operator_won - direct_won)])
            except L.LedgerError:
                raise AdCoinError('offer_budget_spent', status=409) from None
            receipt = self.signer.issue(self.db, 'offer_ack', 'operator:' + operator_ref, {
                'journal_id': journal, 'offer_id': offer_id, 'operator_reward_won': operator_won,
                'user_coins_issued': 0})
        self._after_money_move()
        return {'status': 'acknowledged', 'operator_reward_won': operator_won, 'receipt': receipt}

    # ---------- sponsorship audits ----------
    def record_audit(self, report):
        """Store an audit summary; a failed audit opens the circuit (stop condition 4)."""
        if not isinstance(report, dict) or report.get('profile') != 'ai-ad-coin-sponsorship-audit-v1' \
                or not isinstance(report.get('counts'), dict):
            raise AdCoinError('invalid_audit')
        counts = {k: int(report['counts'].get(k, 0)) for k in ('same', 'changed', 'unstable', 'error')}
        passed = counts['changed'] == 0 and counts['same'] > 0
        changed = [r.get('query') for r in report.get('rows') or [] if isinstance(r, dict)
                   and r.get('verdict') == 'changed'][:20]
        summary = {'counts': counts, 'top': report.get('top'), 'queries': report.get('queries'),
                   'started_at': report.get('started_at'), 'changed_queries': changed,
                   'inconclusive': counts['same'] + counts['changed'] == 0}
        audit_id = 'a_' + uuid.uuid4().hex[:20]
        with self.db.transaction() as db:
            db.execute('INSERT INTO ad_coin_audits VALUES (?,?,?,?)', (audit_id, now(), int(passed), dumps(summary)))
        if not passed and not summary['inconclusive']:
            self.open_circuit('audit_mismatch:%d' % counts['changed'])
        return {'id': audit_id, 'passed': passed, **summary, 'circuit': self.circuit()}

    def audits(self, limit=24):
        rows = self.db.all('SELECT * FROM ad_coin_audits ORDER BY created_at DESC LIMIT ?', (max(1, min(int(limit), 100)),))
        return [{'id': r['id'], 'created_at': int(r['created_at']), 'passed': bool(r['passed']),
                 **json.loads(r['summary'])} for r in rows]

    # ---------- reports ----------
    def receipts(self, user_ref, limit=50):
        rows = self.db.all('SELECT body FROM ad_coin_receipts WHERE user_ref=? ORDER BY created_at DESC LIMIT ?',
                           (user_ref, max(1, min(int(limit), 200))))
        return [json.loads(r['body']) for r in rows]

    def campaign_report(self, campaign_id):
        """Aggregates only: no conversation text, no user identifiers."""
        campaign = self.campaign(campaign_id)
        exposures = self.db.one('SELECT COUNT(*) AS n, COUNT(DISTINCT user_ref) AS people FROM ad_coin_exposures '
                                'WHERE campaign_id=?', (campaign_id,))
        redeemed = self.db.one("SELECT COUNT(*) AS n FROM ad_coin_vouchers v JOIN ad_coin_reservations r ON r.id=v.reservation_id "
                               "WHERE r.campaign_id=? AND v.status='redeemed'", (campaign_id,))
        runs = self.db.one("SELECT COUNT(*) AS n FROM ad_coin_executions e JOIN ad_coin_vouchers v ON v.id=e.source_ref "
                           "JOIN ad_coin_reservations r ON r.id=v.reservation_id WHERE r.campaign_id=? AND e.status='succeeded'",
                           (campaign_id,))
        acks = self.db.one('SELECT COUNT(*) AS n FROM ad_coin_offer_acks WHERE campaign_id=?', (campaign_id,))
        return {'campaign': campaign['id'], 'product': campaign['product'], 'test': campaign['test'],
                'approved_views': exposures['n'], 'people': exposures['people'],
                'sponsored_runs_started': redeemed['n'], 'sponsored_runs_succeeded': runs['n'],
                'agent_receipts': acks['n'], 'escrow_won': campaign['escrow_won'],
                'reward_basis': 'Viewers were rewarded and knew it; views are not purchase intent.'}

    def status(self):
        # Public: the O(1) backing check from the running totals (the full recount runs in the background).
        check = self.ledger.fast_invariant()
        return {'test_mode': self.test_mode, 'payments': 'closed', 'coin_value_won': COIN_VALUE_WON,
                'split_bps': self.split(), 'circuit': self.circuit(),
                'backing': {k: check[k] for k in ('ok', 'problems', 'obligations_won', 'trust_statement_won',
                                                  'coin_liability_won', 'coverage')}}
