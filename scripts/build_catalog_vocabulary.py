"""Build the catalog vocabulary used to correct one-letter typos in requests (2026-11-04).

usage: python -m scripts.build_catalog_vocabulary [out.json]

Reads production PostgreSQL read-only (one connection) and counts, for every lowercase word of
3-20 letters, how many active listings' capability texts contain it. Words in fewer than
MIN_DOCUMENTS listings are left out. The output holds public listing words only.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'agent_market' / 'concierge' / 'catalog_vocabulary.json'
MIN_DOCUMENTS = 5
QUERY = r"""SELECT word, ndoc FROM ts_stat($$SELECT to_tsvector('simple', c.rank_text)
    FROM agentcon_search.capability_text c JOIN resources r ON r.id=c.resource_id WHERE r.active=1$$)
    WHERE word ~ '^[a-z]{3,20}$' AND ndoc >= %d ORDER BY word""" % MIN_DOCUMENTS


def main(out=OUT):
    psql = '/opt/homebrew/opt/postgresql@18/bin/psql'
    dsn = (f"host={ROOT}/gateway-data/postgres18/run port=55432 "
           "dbname=agentcon_cutover_20261020_191757")
    env = {**os.environ, 'PGOPTIONS': '-c default_transaction_read_only=on -c statement_timeout=300s'}
    rows = subprocess.run([psql, dsn, '-AtF', '\t', '-c', QUERY], env=env, check=True,
                          capture_output=True, text=True).stdout.splitlines()
    words = {word: int(count) for word, count in (row.split('\t') for row in rows if '\t' in row)}
    Path(out).write_text(json.dumps({'_about': 'Generated by scripts/build_catalog_vocabulary.py; do not edit.',
                                     'min_documents': MIN_DOCUMENTS, 'words': words},
                                    separators=(',', ':'), sort_keys=True), encoding='utf-8')
    print(len(words), 'words ->', out)


if __name__ == '__main__':
    main(*(sys.argv[1:2]))
