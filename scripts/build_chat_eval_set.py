"""Build the 1k Chat evaluation set from capability families (2026-11-04).

usage: python -m scripts.build_chat_eval_set [families.json] [base_cases.json] [out.json]

Every family gives its written requests plus generated variants: a one-typo request, the
request inside a longer team context, a question form, and (every third family) a protocol
filter. Holdout is chosen per family, so no phrasing of a holdout capability is seen while
tuning. The original hand-written cases keep their own split. Output is deterministic.
"""
import hashlib
import json
import re
import sys

FAMILIES = 'tests/data/chat_eval_families.json'
BASE = 'tests/data/chat_answer_quality_cases.json'
OUT = 'tests/data/chat_answer_quality_cases_1k.json'
HOLDOUT_SHARE = 3  # of 10 families
CONTEXTS = (
    'We are a small team building {what}. Doing this by hand takes hours every week, so we need an agent or API that can {task}. It should be reliable and reasonably cheap.',
    'I run {what} and my current tooling keeps failing. I am looking for something that can {task}, ideally without a long setup.',
    'For {what} we want to automate one step: {task}. Please recommend the best working option.',
    'Context: {what}. Requirement: {task}. Nothing else is needed right now.',
)
SETTINGS = ('an internal dashboard', 'a travel startup', 'a research lab', 'a small online shop',
            'a newsroom tool', 'a customer support desk', 'a hobby project', 'a fintech prototype')
PROTOCOLS = ('mcp', 'a2a', 'x402')


def digest(text):
    return int(hashlib.sha1(text.encode()).hexdigest(), 16)


def typo(text):
    """Swap two inner letters of the longest lowercase word (one deterministic typo)."""
    words = [w for w in re.findall(r'[a-z]{6,}', text)]
    if not words:
        return None
    word = max(words, key=len)
    wrong = word[:2] + word[3] + word[2] + word[4:]
    return text.replace(word, wrong, 1) if wrong != word else None


def cases_for(family):
    fid, base = family['id'], {'type': 'match', 'any': family['any'], 'oracle': family['oracle']}
    group = 'gen-' + family['cat']
    out = []
    for n, task in enumerate(family['en']):
        out.append({'id': f'{fid}-en{n}', 'task': task, 'group': group, 'expect': dict(base)})
    for n, task in enumerate(family.get('ko') or []):
        out.append({'id': f'{fid}-ko{n}', 'task': task, 'group': group + '-ko', 'expect': dict(base)})
    wrong = typo(family['en'][0])
    if wrong:
        out.append({'id': f'{fid}-typo', 'task': wrong, 'group': group + '-typo', 'expect': dict(base)})
    seed = digest(fid)
    long_task = CONTEXTS[seed % len(CONTEXTS)].format(what=SETTINGS[seed % len(SETTINGS)], task=family['en'][1])
    out.append({'id': f'{fid}-long', 'task': long_task, 'group': group + '-long', 'expect': dict(base)})
    out.append({'id': f'{fid}-ask', 'task': f'Is there an agent or API that can {family["en"][2]}?', 'group': group + '-ask',
                'expect': dict(base)})
    if seed % 3 == 0:
        protocol = PROTOCOLS[seed // 3 % len(PROTOCOLS)]
        out.append({'id': f'{fid}-{protocol}', 'task': family['en'][0], 'group': group + '-protocol',
                    'data': {'protocol': protocol}, 'expect': {**base, 'kind': protocol}})
    return out


def build(families_path=FAMILIES, base_path=BASE):
    families = json.load(open(families_path, encoding='utf-8'))['families']
    base = json.load(open(base_path, encoding='utf-8'))
    split, seen = {'tuning': [], 'holdout': []}, set()
    for part in split:
        for case in base[part]:
            # The hand-written file may reuse an id across parts (h1, 11-04); keep both, distinguishable.
            case = dict(case, id=case['id'] + '-' + part) if case['id'] in seen else case
            seen.add(case['id'])
            split[part].append(case)
    for family in families:
        part = 'holdout' if digest(family['id']) % 10 < HOLDOUT_SHARE else 'tuning'
        for case in cases_for(family):
            assert case['id'] not in seen, case['id']
            seen.add(case['id'])
            split[part].append(case)
    return split


if __name__ == '__main__':
    args = sys.argv[1:] + [None] * 3
    result = build(args[0] or FAMILIES, args[1] or BASE)
    with open(args[2] or OUT, 'w', encoding='utf-8') as handle:
        json.dump({'_about': 'Generated by scripts/build_chat_eval_set.py; do not edit by hand.', **result}, handle,
                  ensure_ascii=False, indent=1)
    print({part: len(cases) for part, cases in result.items()})
